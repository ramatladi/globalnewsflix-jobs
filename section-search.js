// The words searched for one section in one language ([] when that language has none).
export function sectionTerms(lang, section) {
  return [...(T[lang]?.[section] || [])];
}
// A search for any of the words: quoted when it has several words (Google News and Bing both read OR).
export function sectionQuery(lang, section) {
  const terms = sectionTerms(lang, section);
  if (!terms.length) return '';
  const q = terms.map(t => /\s/.test(t) ? `"${t}"` : t);
  return q.length === 1 ? q[0] : `(${q.join(' OR ')})`;
}

// The edition's sections to search, fewest stories first (ties in the fixed section order). counts: { section: n }.
export function shortSections(counts, min = EDITION_SECTION_MIN) {
  return EDITION_SECTIONS.map((section, i) => ({ section, i, n: Number(counts?.[section]) || 0 }))
    .filter(x => x.n < min).sort((a, b) => a.n - b.n || a.i - b.i).map(x => x.section);
}
// One section per collector visit: the visit's rotation walks through the short sections.
export function sectionForVisit(sections, rot = 0) {
  const list = (Array.isArray(sections) ? sections : []).filter(s => EDITION_SECTIONS.includes(s));
  return list.length ? list[Math.abs(Number(rot) || 0) % list.length] : '';
}
